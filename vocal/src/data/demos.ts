interface DemoSpec {
  id: string;
  title: string;
  subtitle: string;
  voiceId: string;
  bpm: number;
  beatsPerBar: number;
  style: AccompStyle;
  /** 1 行 = 1 小節のコード進行 */
  chords: string;
  /** メロディと歌詞 */
  seq: string;
  mix?: Partial<MixSettings>;
  expression?: Partial<Expression>;
}

/** 記法をパースして音符に変換する */
function sequence(text: string): VocalNote[] {
  const notes: VocalNote[] = [];
  let at = 0;
  for (const token of text.split(/\s+/).filter(Boolean)) {
    const parts = token.split(':');
    if (parts[0] === 'r') {
      at += Number(parts[1] ?? 1);
      continue;
    }
    const [lyric, name, beats] = parts;
    const length = Number(beats ?? 1);
    notes.push(
      createNote({
        start: at,
        length,
        note: noteNameToMidi(name),
        lyric,
        vel: 0.72,
      })
    );
    at += length;
  }
  return notes;
}

